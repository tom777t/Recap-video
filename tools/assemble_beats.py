# -*- coding: utf-8 -*-
"""
assemble_beats.py - gom `beats.json.d/chunk*.json` thanh `beats_proposal.md`
dung dinh dang ma catalogue.parse_beats / parse_reveal_map / parse_set_pieces
doc duoc.

Khong cham vao beats_proposal.md dang co: ghi ra `beats_proposal_machine.md`
tru khi --out noi khac. File nguoi la du lieu goc, khong phai dau ra.

Dung:
    python tools/assemble_beats.py <project> [--out beats_proposal.md]
                                   [--reveals reveals.json]
"""
from __future__ import annotations
import argparse, io, json, os, sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import config

KINDS = {"setup", "action", "dialogue", "discovery", "reveal", "emotion",
         "aftermath", "transition", "montage"}


def pt(ts) -> float:
    p = [float(x) for x in str(ts).split(":")]
    while len(p) < 3:
        p.insert(0, 0.0)
    return p[0] * 3600 + p[1] * 60 + p[2]


def hms(s: float) -> str:
    s = max(0.0, float(s))
    return f"{int(s)//3600:02d}:{(int(s)%3600)//60:02d}:{int(s)%60:02d}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("project")
    ap.add_argument("--out", default="beats_proposal_machine.md")
    ap.add_argument("--reveals", default="reveals.json",
                    help="JSON {reveals:[{land,hold:[..]}], set_pieces:[...]}")
    ap.add_argument("--title", default=None)
    ap.add_argument("--target", default="18-22 min")
    a = ap.parse_args()
    pdir = config.project_dir(a.project)

    d = pdir / "beats.json.d"
    beats, problems, missing = [], [], []
    files = sorted(d.glob("chunk*.json")) if d.exists() else []
    for f in files:
        try:
            o = json.load(io.open(f, encoding="utf-8"))
        except Exception as e:
            problems.append(f"{f.name}: JSON hong ({e})")
            missing.append(f.name)
            continue
        for i, b in enumerate(o.get("beats") or []):
            try:
                t = pt(b["ts"])
            except Exception:
                problems.append(f"{f.name}#{i}: ts khong doc duoc {b.get('ts')!r}")
                continue
            k = str(b.get("kind", "")).strip().lower()
            if k not in KINDS:
                problems.append(f"{f.name}#{i}: kind={k!r} ngoai tu vung")
                k = "action"
            beats.append({"t": t, "what": str(b.get("what", "")).strip(),
                          "chars": [str(c) for c in (b.get("chars") or [])],
                          "kind": k, "src": f.name})
    if not beats:
        print("khong co beat nao - chua chunk nao duoc viet")
        return 1

    beats.sort(key=lambda x: x["t"])
    # trung thoi diem: giu cai dau, bao cai sau - KHONG lang le bo
    dedup, last = [], None
    for b in beats:
        if last is not None and abs(b["t"] - last) < 1.0:
            problems.append(f"beat trung thoi diem {hms(b['t'])}: "
                            f"{b['what'][:50]!r} (giu cai truoc)")
            continue
        dedup.append(b)
        last = b["t"]
    beats = dedup

    rev, sps = [], []
    rp = pdir / a.reveals
    if rp.exists():
        try:
            rj = json.load(io.open(rp, encoding="utf-8"))
            rev = rj.get("reveals") or []
            sps = rj.get("set_pieces") or []
        except Exception as e:
            problems.append(f"{a.reveals}: {e}")

    title = a.title or a.project
    L = []
    L.append(f"# {title} - Beat List Proposal (MACHINE)")
    L.append("")
    L.append("Generated by tools/make_beats pipeline: shots_machine.json +")
    L.append("transcript.json -> per-chunk subagents -> tools/assemble_beats.py.")
    L.append("NOT hand-written. The timestamps come from machine moment")
    L.append("boundaries, so every beat lands on a real cut.")
    L.append("")
    L.append("style: linear")
    L.append("depth_target: video_essay")
    L.append(f"Target: {a.target}")
    L.append("")
    L.append("KEY: id | ts | what happens | chars | kind")
    L.append("")
    for i, b in enumerate(beats, 1):
        ch = ", ".join(b["chars"]) if b["chars"] else "(none)"
        L.append(f"B{i:02d} | {hms(b['t'])} | {b['what']} | {ch} | {b['kind']}")
    L.append("")

    L.append("```reveal-map")
    if rev:
        for i, r in enumerate(rev, 1):
            hold = ", ".join(str(x) for x in (r.get("hold") or []))
            L.append(f"R{i} | land: {r.get('land')} | hold: {hold}")
    L.append("```")
    L.append("")

    L.append("```set-pieces")
    for i, s in enumerate(sps, 1):
        L.append(f"SP{i} | {s.get('name')} | {s.get('start')} - {s.get('end')} "
                 f"| verified: {s.get('verified','unverified')} | "
                 f"{'keep' if s.get('keep', True) else 'drop'}")
    L.append("```")
    if not sps:
        L.append("")
        L.append("set-pieces: none, because no extended multi-step procedure was "
                 "reported by any chunk.")
    L.append("")

    op = pdir / a.out
    io.open(op, "w", encoding="utf-8").write("\n".join(L))
    print(f"{len(files)} chunk | {len(beats)} beat | {len(rev)} reveal | "
          f"{len(sps)} set-piece")
    print(f"span {hms(beats[0]['t'])} - {hms(beats[-1]['t'])}")
    if problems:
        print(f"\n{len(problems)} van de:")
        for p in problems[:12]:
            print(f"  {p}")
    print(f"\nda ghi {op}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
